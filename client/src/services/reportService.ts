import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

export type ReportColumn<T> = {
  header: string;
  accessor: keyof T | ((row: T) => string | number | boolean | null | undefined);
};

export type ReportMeta = {
  organization?: string;
  department?: string;
  title: string;
  subtitle?: string;
  reportNumber?: string;
  generatedBy?: string;
  filters?: string[];
};

type ExportOptions<T> = {
  meta: ReportMeta;
  data: T[];
  columns: ReportColumn<T>[];
  filename?: string;
};

function getCellValue<T>(
  row: T,
  accessor: ReportColumn<T>["accessor"]
) {
  const value =
    typeof accessor === "function"
      ? accessor(row)
      : row[accessor];

  if (value === null || value === undefined) {
    return "";
  }

  if (typeof value === "boolean") {
    return value ? "Yes" : "No";
  }

  return String(value);
}

function safeFilename(value: string) {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function generateReportNumber(prefix = "JAMII") {
  const now = new Date();

  const year = now.getFullYear();

  const timestamp = [
    now.getMonth() + 1,
    now.getDate(),
    now.getHours(),
    now.getMinutes(),
    now.getSeconds(),
  ]
    .map((value) => String(value).padStart(2, "0"))
    .join("");

  return `${prefix}-${year}-${timestamp}`;
}

export function downloadCSV<T>({
  meta,
  data,
  columns,
  filename,
}: ExportOptions<T>) {
  const headers = columns.map((column) => column.header);

  const rows = data.map((row) =>
    columns.map((column) =>
      getCellValue(row, column.accessor)
    )
  );

  const csvRows = [
    [meta.title],
    meta.subtitle ? [meta.subtitle] : [],
    [],
    headers,
    ...rows,
  ];

  const csv = csvRows
    .map((row) =>
      row
        .map(
          (value) =>
            `"${String(value).replace(/"/g, '""')}"`
        )
        .join(",")
    )
    .join("\n");

  const blob = new Blob([csv], {
    type: "text/csv;charset=utf-8;",
  });

  const url = URL.createObjectURL(blob);

  const link = document.createElement("a");

  link.href = url;

  link.download =
    filename ||
    `${safeFilename(meta.title)}.csv`;

  document.body.appendChild(link);

  link.click();

  document.body.removeChild(link);

  URL.revokeObjectURL(url);
}

export function downloadPDF<T>({
  meta,
  data,
  columns,
  filename,
}: ExportOptions<T>) {
  const doc = new jsPDF({
    orientation: "landscape",
    unit: "mm",
    format: "a4",
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  const organization =
    meta.organization || "Jamii Platform";

  const generatedDate = new Date().toLocaleString();

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);

  doc.text(
    organization,
    14,
    15
  );

  if (meta.department) {
    doc.setFontSize(10);

    doc.setTextColor(90);

    doc.text(
      meta.department,
      14,
      21
    );
  }

  doc.setTextColor(0);

  doc.setFontSize(18);

  doc.text(
    meta.title,
    14,
    32
  );

  if (meta.subtitle) {
    doc.setFont("helvetica", "normal");

    doc.setFontSize(10);

    doc.setTextColor(90);

    doc.text(
      meta.subtitle,
      14,
      38
    );
  }

  doc.setTextColor(0);

  doc.setFont("helvetica", "normal");

  doc.setFontSize(9);

  const reportNumber =
    meta.reportNumber ||
    generateReportNumber("JAMII");

  doc.text(
    `Report No: ${reportNumber}`,
    14,
    47
  );

  doc.text(
    `Generated: ${generatedDate}`,
    14,
    52
  );

  if (meta.generatedBy) {
    doc.text(
      `Generated By: ${meta.generatedBy}`,
      14,
      57
    );
  }

  if (meta.filters?.length) {
    doc.text(
      `Filters: ${meta.filters.join(", ")}`,
      14,
      meta.generatedBy ? 62 : 57
    );
  }

  const startY =
    meta.filters?.length
      ? meta.generatedBy
        ? 69
        : 64
      : meta.generatedBy
        ? 64
        : 59;

  autoTable(doc, {
    startY,

    head: [
      columns.map(
        (column) => column.header
      ),
    ],

    body: data.map((row) =>
      columns.map((column) =>
        getCellValue(
          row,
          column.accessor
        )
      )
    ),

    styles: {
      fontSize: 8,
      cellPadding: 2.5,
      overflow: "linebreak",
    },

    headStyles: {
      fillColor: [35, 35, 35],
      textColor: [255, 255, 255],
      fontStyle: "bold",
    },

    alternateRowStyles: {
      fillColor: [246, 246, 246],
    },

    margin: {
      left: 14,
      right: 14,
    },

    didDrawPage: () => {
      const pageNumber =
        doc.getNumberOfPages();

      doc.setFontSize(8);

      doc.setTextColor(120);

      doc.text(
        `Generated through Jamii Platform`,
        14,
        doc.internal.pageSize.getHeight() - 7
      );

      doc.text(
        `Page ${pageNumber}`,
        pageWidth - 28,
        doc.internal.pageSize.getHeight() - 7
      );

      doc.setTextColor(0);
    },
  });

  doc.save(
    filename ||
      `${safeFilename(meta.title)}.pdf`
  );
}

export function printReport<T>({
  meta,
  data,
  columns,
}: ExportOptions<T>) {
  const printWindow = window.open(
    "",
    "_blank",
    "width=1200,height=800"
  );

  if (!printWindow) {
    window.alert(
      "The browser blocked the print window. Please allow popups for this site."
    );

    return;
  }

  const headers = columns
    .map(
      (column) =>
        `<th>${column.header}</th>`
    )
    .join("");

  const rows = data
    .map(
      (row) => `
        <tr>
          ${columns
            .map(
              (column) =>
                `<td>${getCellValue(
                  row,
                  column.accessor
                )}</td>`
            )
            .join("")}
        </tr>
      `
    )
    .join("");

  const filters =
    meta.filters?.length
      ? `<p><strong>Filters:</strong> ${meta.filters.join(
          ", "
        )}</p>`
      : "";

  printWindow.document.write(`
    <!DOCTYPE html>
    <html>
      <head>
        <title>${meta.title}</title>

        <style>
          * {
            box-sizing: border-box;
          }

          body {
            font-family: Arial, sans-serif;
            padding: 32px;
            color: #111827;
          }

          h1 {
            margin-bottom: 4px;
          }

          h2 {
            margin-top: 4px;
            font-size: 18px;
          }

          .meta {
            margin: 20px 0;
            font-size: 12px;
            color: #475569;
          }

          table {
            width: 100%;
            border-collapse: collapse;
            margin-top: 20px;
            font-size: 11px;
          }

          th,
          td {
            border: 1px solid #cbd5e1;
            padding: 8px;
            text-align: left;
            vertical-align: top;
          }

          th {
            background: #111827;
            color: white;
          }

          tr:nth-child(even) {
            background: #f8fafc;
          }

          .footer {
            margin-top: 30px;
            font-size: 10px;
            color: #64748b;
          }

          @media print {
            body {
              padding: 0;
            }

            @page {
              size: landscape;
              margin: 12mm;
            }
          }
        </style>
      </head>

      <body>
        <h1>
          ${meta.organization || "Jamii Platform"}
        </h1>

        ${
          meta.department
            ? `<p>${meta.department}</p>`
            : ""
        }

        <h2>${meta.title}</h2>

        ${
          meta.subtitle
            ? `<p>${meta.subtitle}</p>`
            : ""
        }

        <div class="meta">
          <p>
            <strong>Report No:</strong>
            ${
              meta.reportNumber ||
              generateReportNumber("JAMII")
            }
          </p>

          <p>
            <strong>Generated:</strong>
            ${new Date().toLocaleString()}
          </p>

          ${
            meta.generatedBy
              ? `<p><strong>Generated By:</strong> ${meta.generatedBy}</p>`
              : ""
          }

          ${filters}
        </div>

        <table>
          <thead>
            <tr>${headers}</tr>
          </thead>

          <tbody>
            ${rows}
          </tbody>
        </table>

        <div class="footer">
          Generated through Jamii Platform
        </div>

        <script>
          window.onload = function () {
            window.print();
          };
        </script>
      </body>
    </html>
  `);

  printWindow.document.close();
}